def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate the Phase 3 results notebook from committed artifacts."
    )
    parser.add_argument(
        "--output", default="notebooks/06_phase3_results.ipynb",
        help="Output notebook path (default: the committed location).",
    )
    parser.add_argument(
        "--skip-path-check", action="store_true",
        help="Do not fail if referenced bundle paths are missing (smoke use).",
    )
    args = parser.parse_args(argv)

    if not args.skip_path_check:
        missing = validate_paths(REPO_ROOT)
        if missing:
            print("[3D.2] BLOCKED — referenced committed artifacts are missing:",
                  file=sys.stderr)
            for p in missing:
                print(f"  - {p}", file=sys.stderr)
            print("\nRefusing to build a notebook that would error on execution.",
                  file=sys.stderr)
            return 1

    nb = build_notebook()
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    nbf.write(nb, str(out))
    print(f"wrote {out}  ({len(nb.cells)} cells)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
