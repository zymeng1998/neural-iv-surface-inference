def md(text: str) -> nbf.NotebookNode:
    return nbf.v4.new_markdown_cell(text)


def code(src: str) -> nbf.NotebookNode:
    return nbf.v4.new_code_cell(src)


def referenced_paths() -> List[str]:
    """Return the committed artifact paths the notebook depends on."""
    return list(REFERENCED_PATHS)


def validate_paths(root: Path = REPO_ROOT) -> List[str]:
    """Return the subset of referenced paths that do not exist under `root`."""
    return [p for p in REFERENCED_PATHS if not (root / p).exists()]


